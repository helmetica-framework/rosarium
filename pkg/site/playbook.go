package site

import (
	"fmt"

	"sigs.k8s.io/yaml"
)

const (
	SiteURL   = "https://docs.helmetica.io"
	SiteTitle = "Helmetica Docs"
	// renovate: datasource=github-releases depName=vshn/antora-ui
	UIBundle = "https://github.com/vshn/antora-ui/releases/download/v3.2.0/ui-bundle.zip"
	editURL  = "https://github.com/helmetica-framework/%s/edit/%s/{path}"
)

// PlaybookInput is everything WritePlaybook needs.
type PlaybookInput struct {
	Sources []Source // repo-backed components
	// BuildRepo is a git repo holding the generated content; StartPaths are
	// the component directories inside it (ROOT and the overlays).
	BuildRepo  string
	StartPaths []string
	UIDir      string
	OutputDir  string
	// SiteURL defaults to SiteURL. Any other URL (a PR preview) is kept
	// out of search engines.
	SiteURL string
}

// WritePlaybook writes the Antora playbook.
func WritePlaybook(path string, in PlaybookInput) error {
	var sources []map[string]any
	attrs := map[string]any{
		"page-pagination": "", "hide-uri-scheme": "", "experimental": "", "icons": "font",
		"kroki-server-url": "https://kroki.vshn.net", "kroki-fetch-diagram": "",
	}
	for _, s := range in.Sources {
		sources = append(sources, map[string]any{
			"url":        s.LocalDir,
			"branches":   "HEAD",
			"start_path": "docs",
			"edit_url":   fmt.Sprintf(editURL, s.Repo.Name, s.Branch),
		})
		attrs["rosarium-has-"+s.Name] = ""
	}
	if in.BuildRepo != "" {
		sources = append(sources, map[string]any{
			"url":         in.BuildRepo,
			"branches":    "HEAD",
			"start_paths": in.StartPaths,
			"edit_url":    false,
		})
	}
	url, robots := in.SiteURL, "allow"
	if url == "" {
		url = SiteURL
	}
	if url != SiteURL {
		robots = "disallow"
	}
	pb := map[string]any{
		"site": map[string]any{
			"title":      SiteTitle,
			"url":        url,
			"start_page": "ROOT::index.adoc",
			"robots":     robots,
			"keys":       map[string]any{"search_page_path": "search.html"},
		},
		"content": map[string]any{"sources": sources},
		"ui": map[string]any{
			"bundle":             map[string]any{"url": UIBundle, "snapshot": false},
			"supplemental_files": in.UIDir,
		},
		"asciidoc": map[string]any{
			"attributes": attrs,
			"extensions": []string{"asciidoctor-kroki"},
		},
		"output": map[string]any{"dir": in.OutputDir, "clean": true},
	}
	b, err := yaml.Marshal(pb)
	if err != nil {
		return err
	}
	return writeFile(path, "# Generated by rosarium. Do not edit.\n"+string(b))
}
