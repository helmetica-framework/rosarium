package site

import (
	"fmt"
	"path/filepath"
	"slices"
	"strings"

	"github.com/helmetica-framework/rosarium/pkg/schemadoc"
)

const generatedHeader = ":page-generated: true\n// Generated by rosarium — edit the chart/CRD, not this file.\n"

// WriteOverlay writes the generated pages of s as an extra content source
// for the same Antora component (outDir/generated/<name>). It returns ""
// when there is nothing to generate.
func WriteOverlay(outDir string, s Source) (string, error) {
	if s.Reagent == nil && len(s.CRDs) == 0 {
		return "", nil
	}
	dir := filepath.Join(outDir, "generated", s.Name)
	mod := filepath.Join(dir, "modules", "ROOT")
	nav := ".Generated reference\n"

	if r := s.Reagent; r != nil {
		nav += "* xref:references/parameters.adoc[Parameters]\n"
		var b strings.Builder
		b.WriteString("= Parameters\n" + generatedHeader + "\n")
		b.WriteString("The values you can set in `spec.values` of an instance.\n\n")
		if len(r.Fields) == 0 {
			b.WriteString("This reagent exposes no parameters yet.\n")
		} else if err := schemadoc.RenderTable(&b, r.Fields); err != nil {
			return "", err
		}
		if err := writeFile(filepath.Join(mod, "pages", "references", "parameters.adoc"), b.String()); err != nil {
			return "", err
		}
		example := "// Generated by rosarium.\n[source,yaml]\n----\n" + r.Example + "----\n\n" +
			"NOTE: The exact `apiVersion` and `kind` depend on how your platform registers this reagent (its ClaimDefinition).\n"
		if err := writeFile(filepath.Join(mod, "partials", "order-example.adoc"), example); err != nil {
			return "", err
		}
	}

	if len(s.CRDs) > 0 {
		nav += "* xref:references/api.adoc[API reference]\n"
		var b strings.Builder
		b.WriteString("= API reference\n" + generatedHeader + ":toclevels: 1\n\n")
		for _, c := range s.CRDs {
			fmt.Fprintf(&b, "== %s\n\n", c.Kind)
			for _, v := range c.Versions {
				fmt.Fprintf(&b, "`%s/%s`, %s\n\n", c.Group, v.Name, strings.ToLower(c.Scope))
				if v.Description != "" {
					b.WriteString(strings.ReplaceAll(v.Description, "{", `\{`) + "\n\n")
				}
				for _, part := range []struct {
					title  string
					fields []schemadoc.Field
				}{{"Spec", v.Spec}, {"Status", v.Status}} {
					if len(part.fields) == 0 {
						continue
					}
					fmt.Fprintf(&b, "=== %s\n\n", part.title)
					if err := schemadoc.RenderTable(&b, part.fields); err != nil {
						return "", err
					}
					b.WriteString("\n")
				}
			}
		}
		if err := writeFile(filepath.Join(mod, "pages", "references", "api.adoc"), b.String()); err != nil {
			return "", err
		}
	}

	if err := writeFile(filepath.Join(mod, "generated-nav.adoc"), nav); err != nil {
		return "", err
	}
	// Antora keeps the nav of the last descriptor of a component version, and
	// the overlay is read last: repeat the repo's nav files, then add ours.
	var antora strings.Builder
	fmt.Fprintf(&antora, "name: %s\nversion: ~\nnav:\n", s.Name)
	for _, n := range append(slices.Clone(s.Nav), "modules/ROOT/generated-nav.adoc") {
		fmt.Fprintf(&antora, "- %s\n", n)
	}
	return dir, writeFile(filepath.Join(dir, "antora.yml"), antora.String())
}
