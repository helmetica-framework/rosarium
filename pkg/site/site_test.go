func TestWriteSidebar(t *testing.T) {
	p := filepath.Join(t.TempDir(), "nav-explore.hbs")
	root := Source{Name: "ROOT", Title: "Helmetica Framework", Group: config.GroupFramework}
	if err := WriteSidebar(p, []Source{adept(), redis(), root}); err != nil {
		t.Fatal(err)
	}
	s := read(t, p)
	iFw, iRe, iOp := strings.Index(s, ">Framework<"), strings.Index(s, ">Reagents<"), strings.Index(s, ">Operators<")
	if iFw < 0 || iRe < iFw || iOp < iRe {
		t.Errorf("groups out of order (%d %d %d):\n%s", iFw, iRe, iOp, s)
	}
	if strings.Contains(s, ">Platform<") || strings.Contains(s, ">Building reagents<") {
		t.Error("empty groups rendered")
	}
	cat, red := strings.Index(s, "relativize '/reagents.html'"), strings.Index(s, `lookup @root.site.components "reagent-redis"`)
	if cat < 0 || red < cat {
		t.Errorf("catalogue must come first in Reagents group:\n%s", s)
	}
}

func TestWritePlaybook(t *testing.T) {
	p := filepath.Join(t.TempDir(), "playbook.yml")
	r := redis()
	r.LocalDir = "/cache/reagent-redis"
	err := WritePlaybook(p, PlaybookInput{
		Sources:    []Source{r},
		BuildRepo:  "/build",
		StartPaths: []string{"root", "generated/reagent-redis"},
		UIDir:      "/build/ui",
		OutputDir:  "/build/_public",
	})
	if err != nil {
		t.Fatal(err)
	}
	var pb map[string]any
	if err := yaml.Unmarshal([]byte(read(t, p)), &pb); err != nil {
		t.Fatal(err)
	}
	site := pb["site"].(map[string]any)
	if site["url"] != "https://docs.helmetica.io" || site["title"] != "Helmetica Docs" || site["start_page"] != "ROOT::index.adoc" {
		t.Errorf("site = %v", site)
	}
	srcs := pb["content"].(map[string]any)["sources"].([]any)
	if len(srcs) != 2 {
		t.Fatalf("want repo source + build source, got %v", srcs)
	}
	s0 := srcs[0].(map[string]any)
	if s0["url"] != "/cache/reagent-redis" || s0["branches"] != "HEAD" || s0["start_path"] != "docs" ||
		s0["edit_url"] != "https://github.com/helmetica-framework/reagent-redis/edit/main/{path}" {
		t.Errorf("source = %v", s0)
	}
	s1 := srcs[1].(map[string]any)
	if s1["url"] != "/build" || len(s1["start_paths"].([]any)) != 2 || s1["edit_url"] != false {
		t.Errorf("build source = %v", s1)
	}
	ui := pb["ui"].(map[string]any)
	if ui["bundle"].(map[string]any)["url"] != "https://github.com/vshn/antora-ui/releases/download/v3.2.0/ui-bundle.zip" || ui["supplemental_files"] != "/build/ui" {
		t.Errorf("ui = %v", ui)
	}
	attrs := pb["asciidoc"].(map[string]any)["attributes"].(map[string]any)
	if _, ok := attrs["rosarium-has-reagent-redis"]; !ok {
		t.Errorf("missing rosarium-has-reagent-redis attribute: %v", attrs)
	}
	if pb["output"].(map[string]any)["dir"] != "/build/_public" {
		t.Errorf("output = %v", pb["output"])
	}
}

