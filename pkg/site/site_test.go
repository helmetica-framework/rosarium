func TestReadAntoraYML(t *testing.T) {
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "antora.yml"), []byte("name: reagent-redis\ntitle: Redis\nversion: ~\nnav:\n- modules/ROOT/nav.adoc\n"), 0o644)
	d, err := ReadAntoraYML(dir)
	if err != nil || d.Name != "reagent-redis" || d.Title != "Redis" || len(d.Nav) != 1 || d.Nav[0] != "modules/ROOT/nav.adoc" {
		t.Fatalf("got %+v %v", d, err)
	}
	os.WriteFile(filepath.Join(dir, "antora.yml"), []byte("name: x\nversion: master\n"), 0o644)
	if _, err := ReadAntoraYML(dir); err == nil || !strings.Contains(err.Error(), "version: ~") {
		t.Fatalf("want versionless error, got %v", err)
	}
}

func TestWriteOverlay_Reagent(t *testing.T) {
	out := t.TempDir()
	dir, err := WriteOverlay(out, redis())
	if err != nil {
		t.Fatal(err)
	}
	if dir != filepath.Join(out, "generated", "reagent-redis") {
		t.Errorf("dir = %s", dir)
	}
	a := read(t, filepath.Join(dir, "antora.yml"))
	// Antora takes nav from the last descriptor, so the overlay repeats the repo's nav.
	if a != "name: reagent-redis\nversion: ~\nnav:\n- modules/ROOT/nav.adoc\n- modules/ROOT/generated-nav.adoc\n" {
		t.Errorf("antora.yml = %q", a)
	}
	contains(t, "nav", read(t, filepath.Join(dir, "modules/ROOT/generated-nav.adoc")), "xref:references/parameters.adoc[Parameters]")
	contains(t, "parameters", read(t, filepath.Join(dir, "modules/ROOT/pages/references/parameters.adoc")),
		"= Parameters", "// Generated by rosarium", "pass:c[service.plan]", "|===")
	contains(t, "order example", read(t, filepath.Join(dir, "modules/ROOT/partials/order-example.adoc")),
		"[source,yaml]", "kind: Redis", "ClaimDefinition")
}

