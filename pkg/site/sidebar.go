package site

import (
	"fmt"
	"html"
	"sort"
	"strings"

	"github.com/helmetica-framework/rosarium/pkg/config"
)

// WriteSidebar writes a nav-explore.hbs override for the UI bundle that
// lists components grouped by role (config.GroupOrder) instead of one flat list.
func WriteSidebar(path string, sources []Source) error {
	byGroup := map[config.Group][]Source{}
	for _, s := range sources {
		byGroup[s.Group] = append(byGroup[s.Group], s)
	}
	var b strings.Builder
	b.WriteString(`{{!-- Generated by rosarium: components grouped by role. --}}
<div class="nav-panel-explore{{#unless page.navigation}} is-active{{/unless}}" data-panel="explore">
  {{#if page.component}}
  <div class="context">
    <span class="title">{{page.component.title}}</span>
  </div>
  {{/if}}
  <ul class="components">
`)
	for _, g := range config.GroupOrder {
		list := byGroup[g]
		if len(list) == 0 {
			continue
		}
		sort.Slice(list, func(i, j int) bool { return list[i].Title < list[j].Title })
		fmt.Fprintf(&b, "    <li class=\"component-group\"><span class=\"group-title\">%s</span>\n      <ul class=\"group-components\">\n", html.EscapeString(string(g)))
		if g == config.GroupReagents {
			b.WriteString("        <li class=\"component\"><a class=\"title\" href=\"{{{relativize '/reagents.html'}}}\">Catalogue</a></li>\n")
		}
		for _, s := range list {
			fmt.Fprintf(&b, "        {{#with (lookup @root.site.components %q)}}<li class=\"component{{#if (eq this @root.page.component)}} is-current{{/if}}\"><a class=\"title\" href=\"{{{relativize ./url}}}\">{{{./title}}}</a></li>{{/with}}\n", s.Name)
		}
		b.WriteString("      </ul>\n    </li>\n")
	}
	b.WriteString("  </ul>\n</div>\n")
	return writeFile(path, b.String())
}
