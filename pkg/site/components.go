package site

import (
	"fmt"
	"sort"
	"strings"

	"github.com/helmetica-framework/rosarium/pkg/config"
)

// WriteComponents writes the landing page's component index: every system
// component grouped by role, each with its GitHub description. Reagents are
// summarised as one link to the catalogue so the index stays short.
func WriteComponents(path string, sources []Source) error {
	byGroup := map[config.Group][]Source{}
	for _, s := range sources {
		byGroup[s.Group] = append(byGroup[s.Group], s)
	}
	var b strings.Builder
	b.WriteString("// Generated by rosarium: all components grouped by role.\n[.component-index]\n--\n")
	for _, g := range config.GroupOrder {
		list := byGroup[g]
		switch {
		case g == config.GroupFramework:
			continue
		case g == config.GroupReagents:
			fmt.Fprintf(&b, ".%s\n* xref:reagents.adoc[Reagent catalogue]: %s\n\n", g, reagentCount(len(list)))
			continue
		case len(list) == 0:
			continue
		}
		sort.Slice(list, func(i, j int) bool { return list[i].Title < list[j].Title })
		fmt.Fprintf(&b, ".%s\n", g)
		for _, s := range list {
			fmt.Fprintf(&b, "* xref:%s::index.adoc[%s]", s.Name, s.Title)
			if d := plain(s.Repo.Description); d != "" {
				b.WriteString(": " + d)
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	b.WriteString("--\n")
	return writeFile(path, b.String())
}

func reagentCount(n int) string {
	switch n {
	case 0:
		return "none published yet"
	case 1:
		return "1 reagent"
	default:
		return fmt.Sprintf("%d reagents", n)
	}
}
